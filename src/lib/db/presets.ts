export function builtInPresetRecords(): DirectionPreset[] {
  const now = nowIso();
  return BUILT_IN_PRESETS.map((p, i) => ({ ...p, builtIn: true, order: i, updatedAt: now }));
}

export function originalPreset(id: string): Def | undefined {
  return BUILT_IN_PRESETS.find((p) => p.id === id);
}
